"""Render the platform global Claude assets into a consumer repo.

    python claude-global/sync.py <consumer-dir> --tag <platform-tag> [--check]

Writes (all under the consumer repo):
  .claude/rules/platform-<name>.md      from rules/<name>.md
  .claude/hooks/platform-<name>         from hooks/<name>
  .claude/settings.json                 platform hook entries merged in
  CLAUDE.md                             a managed block of @-imports

Files named platform-* are owned by this script (stale ones are removed).
Everything else in the consumer is left alone. --check changes nothing and
exits 1 when the consumer differs from what a sync would produce.
Stdlib only.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEGIN = "<!-- platform:begin (generated by platform claude-global/sync.py, do not edit) -->"
END = "<!-- platform:end -->"
HOOK_MARK = ".claude/hooks/platform-"


def _norm(text):
    return text.replace("\r\n", "\n")


def _read(path):
    return _norm(path.read_text(encoding="utf-8")) if path.exists() else None


def render_rule(name, body, tag):
    head = "<!-- GENERATED from platform@%s, do not edit. Source: claude-global/rules/%s.md -->\n" % (tag, name)
    return head + _norm(body)


def render_hook(name, body, tag):
    head = "# GENERATED from platform@%s, do not edit. Source: claude-global/hooks/%s\n" % (tag, name)
    return head + _norm(body)


def _is_managed(entry):
    return any(HOOK_MARK in h.get("command", "") for h in entry.get("hooks", []))


def merge_settings(existing, fragment):
    """Merge platform hook entries into a settings dict (idempotent)."""
    out = json.loads(json.dumps(existing or {}))
    for key in fragment:
        if key != "hooks":
            raise ValueError("settings.fragment.json: unsupported key %r" % key)
    hooks = out.setdefault("hooks", {})
    for event, entries in fragment.get("hooks", {}).items():
        kept = [e for e in hooks.get(event, []) if not _is_managed(e)]
        hooks[event] = entries + kept
    return out


def desired(source, target, tag):
    """Return ({relpath: content}, set(owned relpaths currently in target))."""
    want = {}
    rules = sorted((source / "rules").glob("*.md"))
    for p in rules:
        want[".claude/rules/platform-%s.md" % p.stem] = render_rule(p.stem, p.read_text(encoding="utf-8"), tag)
    for p in sorted((source / "hooks").glob("*")):
        if p.is_file():
            name = p.name if p.name.startswith("platform-") else "platform-" + p.name
            want[".claude/hooks/" + name] = render_hook(p.name, p.read_text(encoding="utf-8"), tag)

    fragment = json.loads((source / "settings.fragment.json").read_text(encoding="utf-8"))
    cur = _read(target / ".claude/settings.json")
    merged = merge_settings(json.loads(cur) if cur else {}, fragment)
    want[".claude/settings.json"] = json.dumps(merged, indent=2) + "\n"

    imports = "\n".join("@.claude/rules/platform-%s.md" % p.stem for p in rules)
    block = BEGIN + "\n" + imports + "\n" + END
    claude = _read(target / "CLAUDE.md")
    if claude is None:
        claude = ("# CLAUDE.md\n\nDomain rules for this repo go here. "
                  "Global rules come from the platform block below.\n\n" + block + "\n")
    elif BEGIN in claude and END in claude:
        a = claude.index(BEGIN)
        b = claude.index(END) + len(END)
        claude = claude[:a] + block + claude[b:]
    else:
        claude = claude.rstrip("\n") + "\n\n" + block + "\n"
    want["CLAUDE.md"] = claude

    owned = set()
    for sub in (".claude/rules", ".claude/hooks"):
        d = target / sub
        if d.is_dir():
            owned |= {sub + "/" + f.name for f in d.iterdir() if f.name.startswith("platform-")}
    return want, owned


def run(source, target, tag, check=False):
    """Apply (or with check=True only report) a sync. Returns a list of changes."""
    want, owned = desired(Path(source), Path(target), tag)
    changes = []
    for rel, content in want.items():
        if _read(Path(target) / rel) != content:
            changes.append("write " + rel)
            if not check:
                path = Path(target) / rel
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    for rel in sorted(owned - set(want)):
        changes.append("remove " + rel)
        if not check:
            (Path(target) / rel).unlink()
    return changes


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("target")
    ap.add_argument("--tag", required=True, help="platform tag the assets come from, e.g. v0.2.0")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--source", default=str(HERE))
    args = ap.parse_args(argv)
    changes = run(args.source, args.target, args.tag, check=args.check)
    for c in changes:
        print(c)
    if args.check and changes:
        print("DRIFT: run sync.py --tag %s on this repo" % args.tag, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
